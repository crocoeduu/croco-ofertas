import { beforeEach, afterEach, it, expect, vi } from 'vitest';
import { randomBytes } from 'node:crypto';
import { NextRequest } from 'next/server';
import { renderToStaticMarkup } from 'react-dom/server';
import { tokenFixture } from './fixtures';
import { digest, decrypt, type EncryptedValue } from '@/lib/crypto';
const memory = vi.hoisted(() => ({ query: vi.fn(), session: undefined as string | undefined }));
vi.mock('@/lib/database', () => ({ getDatabase: () => ({ query: memory.query }) }));
vi.mock('next/headers', () => ({ cookies: async () => ({ get: (name: string) => name === '__Host-croco_session' && memory.session ? { value: memory.session } : undefined }) }));
import { GET as login } from '@/app/api/mercadolivre/login/route';
import { GET as callback } from '@/app/api/mercadolivre/callback/route';
import Home from '@/app/page';
const key = randomBytes(32);
beforeEach(() => {
  vi.stubEnv('NODE_ENV', 'production');
  vi.stubEnv('MELI_CLIENT_ID', '123456');
  vi.stubEnv('MELI_CLIENT_SECRET', 'unit-secret-placeholder');
  vi.stubEnv('MELI_REDIRECT_URI', 'https://example.com/api/mercadolivre/callback');
  vi.stubEnv('DATABASE_URL', 'postgres://localhost/db?sslmode=verify-full');
  vi.stubEnv('TOKEN_ENCRYPTION_KEY', key.toString('hex'));
  vi.stubGlobal('fetch', vi.fn<typeof fetch>().mockResolvedValue(Response.json(tokenFixture)));
  memory.session = undefined;
  memory.query.mockReset();
});
afterEach(() => { vi.unstubAllEnvs(); vi.unstubAllGlobals(); });
it('login → callback → tokens AES-GCM → sessão → interface conectada', async () => {
  memory.query.mockResolvedValue({ rowCount: 1, rows: [{ hits: 1 }] });
  const start = await login(new NextRequest('https://example.com/api/mercadolivre/login'));
  expect(start.status).toBe(302);
  const state = start.cookies.get('__Host-meli_state')!.value;
  const verifier = start.cookies.get('__Host-meli_pkce')!.value;
  const finish = await callback(new NextRequest(`https://example.com/api/mercadolivre/callback?state=${state}&code=unit-code`, {
    headers: { cookie: `__Host-meli_state=${state}; __Host-meli_pkce=${verifier}` }
  }));
  expect(finish.status).toBe(303);
  expect(finish.headers.get('location')).toBe('https://example.com/');
  const session = finish.cookies.get('__Host-croco_session')!;
  expect(session.value).toMatch(/^[A-Za-z0-9_-]{43}$/);
  expect(finish.headers.get('set-cookie')).toContain('HttpOnly');
  expect(finish.headers.get('set-cookie')).toContain('Secure');
  const insert = memory.query.mock.calls.find(([sql]) => sql.includes('INSERT INTO meli_connections'))!;
  expect(insert).toBeDefined();
  const values = insert[1];
  expect(values[0]).toBe(digest(session.value));
  expect(decrypt(values[2] as EncryptedValue, key, `${values[0]}:access`)).toBe(tokenFixture.access_token);
  expect(decrypt(values[3] as EncryptedValue, key, `${values[0]}:refresh`)).toBe(tokenFixture.refresh_token);
  expect(JSON.stringify(values)).not.toContain(tokenFixture.access_token);
  expect(JSON.stringify(values)).not.toContain(tokenFixture.refresh_token);
  memory.session = session.value;
  const html = renderToStaticMarkup(await Home({ searchParams: Promise.resolve({}) }));
  expect(html).toContain('Conectado');
  expect(html).toContain('RECONECTAR MERCADO LIVRE');
  expect(html).not.toContain(tokenFixture.access_token);
  expect(html).not.toContain(tokenFixture.refresh_token);
});
it('falha de persistência não cria sessão nem mostra conexão concluída', async () => {
  memory.query.mockResolvedValue({ rowCount: 1, rows: [{ hits: 1 }] });
  const start = await login(new NextRequest('https://example.com/api/mercadolivre/login'));
  const state = start.cookies.get('__Host-meli_state')!.value;
  const verifier = start.cookies.get('__Host-meli_pkce')!.value;
  memory.query.mockReset().mockResolvedValueOnce({ rowCount: 1, rows: [{ hits: 1 }] }).mockResolvedValueOnce({ rowCount: 1 }).mockRejectedValueOnce(Object.assign(new Error('private-db-detail'), { code: '28P01' }));
  const logger = vi.spyOn(console, 'error').mockImplementation(() => undefined);
  const finish = await callback(new NextRequest(`https://example.com/api/mercadolivre/callback?state=${state}&code=unit-code`, { headers: { cookie: `__Host-meli_state=${state}; __Host-meli_pkce=${verifier}` } }));
  expect(finish.status).toBe(503);
  expect(finish.cookies.get('__Host-croco_session')).toBeUndefined();
  expect(logger).toHaveBeenCalledExactlyOnceWith('DB_AUTH_FAILED', expect.objectContaining({sqlstate:'28P01'}));
  expect(await finish.text()).not.toContain('private-db-detail');
  logger.mockRestore();
});
